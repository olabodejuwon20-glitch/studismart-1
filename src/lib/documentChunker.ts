// Intelligent chunking and section extraction for university textbooks,
// multi-week lecture handouts, and long course materials.

export interface DocumentSection {
  id: string;
  title: string;
  text: string;
  wordCount: number;
  startPage?: number;
  endPage?: number;
}

export interface DocumentAnalysis {
  totalWords: number;
  estimatedPages: number;
  estimatedReadMinutes: number;
  sections: DocumentSection[];
  suggestedQuestionCount: number;
}

/**
 * Heuristically identifies chapter, module, or topic headers across long documents.
 */
const SECTION_HEADER_REGEX = /(?:^|\n)(?:(?:#{1,3}\s+)|(?:(?:CHAPTER|MODULE|UNIT|LECTURE|WEEK|TOPIC|PART|SECTION)\s+[0-9IVXLCDM]+[:\.\s\-]+)|(?:\b[0-9]{1,2}\.[0-9]{1,2}\s+[A-Z]))([^\n]{3,80})(?:\n|$)/gi;

/**
 * Parses raw extracted text into structured logical sections.
 */
export function parseDocumentSections(rawText: string): DocumentSection[] {
  if (!rawText || rawText.trim().length === 0) return [];

  const text = rawText.trim();
  const sections: DocumentSection[] = [];

  // Look for [Page X] markers if generated by PDF extractor
  const pageMatches = [...text.matchAll(/\[Page\s+(\d+)\]/gi)];
  const pageMap = new Map<number, number>(); // charIndex -> pageNum
  for (const m of pageMatches) {
    if (m.index !== undefined) {
      pageMap.set(m.index, parseInt(m[1], 10));
    }
  }

  // Find heading boundaries
  const matches = [...text.matchAll(SECTION_HEADER_REGEX)];

  if (matches.length >= 2) {
    for (let i = 0; i < matches.length; i++) {
      const match = matches[i];
      const startIdx = match.index ?? 0;
      const endIdx = i < matches.length - 1 ? (matches[i + 1].index ?? text.length) : text.length;

      const title = match[0].replace(/^[#\s\n]+/, "").trim();
      const sectionContent = text.slice(startIdx, endIdx).trim();
      const words = sectionContent.split(/\s+/).filter(Boolean).length;

      // Only include sections with meaningful content
      if (words >= 30) {
        sections.push({
          id: `sec_${i + 1}`,
          title: title.slice(0, 100),
          text: sectionContent,
          wordCount: words,
        });
      }
    }
  }

  // Fallback: If no explicit chapter headings found, split into ~3,000-word logical chunks
  if (sections.length === 0) {
    const CHUNK_WORDS = 3000;
    const words = text.split(/\s+/).filter(Boolean);
    const totalWords = words.length;

    if (totalWords <= CHUNK_WORDS * 1.5) {
      sections.push({
        id: "sec_full",
        title: "Complete Material",
        text,
        wordCount: totalWords,
      });
    } else {
      let currentWordIdx = 0;
      let partIdx = 1;

      while (currentWordIdx < totalWords) {
        const slice = words.slice(currentWordIdx, currentWordIdx + CHUNK_WORDS);
        const chunkText = slice.join(" ");
        sections.push({
          id: `part_${partIdx}`,
          title: `Part ${partIdx}`,
          text: chunkText,
          wordCount: slice.length,
        });
        currentWordIdx += CHUNK_WORDS;
        partIdx++;
      }
    }
  }

  return sections;
}

/**
 * Analyzes full document text to give deep statistics and recommended question counts.
 */
export function analyzeDocument(rawText: string): DocumentAnalysis {
  const words = rawText.trim().split(/\s+/).filter(Boolean).length;
  const sections = parseDocumentSections(rawText);

  // ~350 words per page average in academic reading
  const estimatedPages = Math.max(1, Math.round(words / 350));
  // Average reading speed: 200 words per minute
  const estimatedReadMinutes = Math.max(1, Math.round(words / 200));

  // Balanced target: 1 question per ~40-60 words up to max 100
  const suggestedQuestionCount = Math.max(10, Math.min(100, Math.floor(words / 45)));

  return {
    totalWords: words,
    estimatedPages,
    estimatedReadMinutes,
    sections,
    suggestedQuestionCount,
  };
}

/**
 * Calculates how many questions each section should contribute
 * to ensure balanced, whole-syllabus coverage.
 */
export function getSectionQuestionDistribution(
  sections: DocumentSection[],
  totalTarget: number
): { section: DocumentSection; count: number }[] {
  if (sections.length === 0) return [];
  if (sections.length === 1) return [{ section: sections[0], count: totalTarget }];

  const totalWords = sections.reduce((sum, s) => sum + s.wordCount, 0);
  let allocated = 0;

  const distribution = sections.map((sec, idx) => {
    // Proportional allocation with minimum 1 per section if target allows
    const share = sec.wordCount / (totalWords || 1);
    let count = Math.max(1, Math.round(share * totalTarget));

    // Ensure we don't overshoot on the last item
    if (idx === sections.length - 1) {
      count = Math.max(1, totalTarget - allocated);
    } else {
      allocated += count;
    }

    return { section: sec, count };
  });

  return distribution;
}
